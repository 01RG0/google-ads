"""
Phase 2 - Analyze the captured HAR and write docs/endpoints.md.

Usage:
    python -I scripts/analyze_har.py
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import parse_qs, urlparse

HAR_PATH = Path(__file__).parent.parent / "captures" / "adstransparency.har"
DOCS_PATH = Path(__file__).parent.parent / "docs" / "endpoints.md"
SAMPLES_DIR = Path(__file__).parent.parent / "docs" / "samples"
DOCS_PATH.parent.mkdir(parents=True, exist_ok=True)
SAMPLES_DIR.mkdir(parents=True, exist_ok=True)

# Headers that carry no API-relevant info and just add noise
NOISE_HEADERS = {
    "accept-encoding", "accept-language", "cache-control", "connection",
    "dnt", "origin", "pragma", "referer", "sec-ch-ua", "sec-ch-ua-mobile",
    "sec-ch-ua-platform", "sec-fetch-dest", "sec-fetch-mode", "sec-fetch-site",
    "upgrade-insecure-requests", "user-agent", "x-forwarded-for",
    "content-length",
}


def classify_url(url: str) -> str | None:
    """Return a short label for URLs that look like API calls, else None."""
    p = urlparse(url)
    if "adstransparency.google.com" not in p.netloc:
        return None
    path = p.path.lower()
    qs = parse_qs(p.query)

    # Filter out static assets / tracking pixels
    static_exts = (".js", ".css", ".png", ".ico", ".woff", ".woff2", ".svg", ".gif")
    if any(path.endswith(e) for e in static_exts):
        return None
    if "/static/" in path or "/_/scs/" in path:
        return None

    return path or "/"


def important_headers(headers: list[dict]) -> dict:
    return {
        h["name"]: h["value"]
        for h in headers
        if h["name"].lower() not in NOISE_HEADERS
        and not h["name"].lower().startswith(":")
    }


def summarize_json(obj, depth=0, max_depth=3) -> str:
    """Produce a compact type-annotated skeleton of a JSON value."""
    if depth > max_depth:
        return "..."
    if isinstance(obj, dict):
        items = []
        for k, v in list(obj.items())[:20]:
            items.append(f"  {'  '*depth}{k!r}: {summarize_json(v, depth+1, max_depth)}")
        suffix = "\n  ...more keys" if len(obj) > 20 else ""
        return "{\n" + ",\n".join(items) + suffix + "\n" + "  "*depth + "}"
    if isinstance(obj, list):
        if not obj:
            return "[]"
        sample = summarize_json(obj[0], depth+1, max_depth)
        return f"[  /* {len(obj)} items */  {sample}  ]"
    if obj is None:
        return "null"
    return type(obj).__name__


def main() -> None:
    if not HAR_PATH.exists():
        print(f"HAR not found at {HAR_PATH}. Run capture_har.py first.")
        sys.exit(1)

    with open(HAR_PATH, encoding="utf-8") as f:
        har = json.load(f)

    entries = har.get("log", {}).get("entries", [])
    print(f"Total HAR entries: {len(entries)}")

    # Group by (method, path_template)
    grouped: dict[str, list[dict]] = defaultdict(list)
    for entry in entries:
        req = entry["request"]
        url = req["url"]
        label = classify_url(url)
        if label is None:
            continue
        key = f"{req['method']} {label}"
        grouped[key].append(entry)

    print(f"Distinct API endpoints found: {len(grouped)}")

    lines = [
        "# Google Ads Transparency Center — Endpoint Findings",
        "",
        "> Auto-generated by `scripts/analyze_har.py`.  "
        "Do not commit the HAR file (contains raw responses).",
        "",
        "## Summary",
        "",
        f"| # | Method | Path | Calls observed |",
        "|---|--------|------|----------------|",
    ]
    sorted_keys = sorted(grouped.keys())
    for i, key in enumerate(sorted_keys, 1):
        method, path = key.split(" ", 1)
        lines.append(f"| {i} | `{method}` | `{path}` | {len(grouped[key])} |")

    lines += ["", "---", ""]

    dynamic_token_warning = False

    for key in sorted_keys:
        method, path = key.split(" ", 1)
        entries_for_key = grouped[key]
        first = entries_for_key[0]
        req = first["request"]
        resp = first.get("response", {})

        lines += [f"## `{method} {path}`", ""]
        lines.append(f"**Calls observed:** {len(entries_for_key)}")
        lines.append("")

        # URL params
        parsed = urlparse(req["url"])
        qs = parse_qs(parsed.query, keep_blank_values=True)
        if qs:
            lines.append("### Query parameters")
            lines.append("")
            for k, vs in qs.items():
                lines.append(f"- `{k}` = `{vs[0]}`")
            lines.append("")

        # Request headers that matter
        imp_req_hdrs = important_headers(req.get("headers", []))
        if imp_req_hdrs:
            lines.append("### Notable request headers")
            lines.append("")
            for k, v in imp_req_hdrs.items():
                # Flag potential token-bearing headers
                if any(tok in k.lower() for tok in ("token", "auth", "key", "secret", "sign")):
                    dynamic_token_warning = True
                    lines.append(f"- `{k}`: `{v}` ⚠️  **possible dynamic token**")
                else:
                    lines.append(f"- `{k}`: `{v}`")
            lines.append("")

        # Request body
        post_data = req.get("postData", {})
        if post_data:
            lines.append("### Request body")
            lines.append("")
            mime = post_data.get("mimeType", "")
            text = post_data.get("text", "")
            if "json" in mime:
                try:
                    body_obj = json.loads(text)
                    lines.append("```json")
                    lines.append(json.dumps(body_obj, indent=2)[:2000])
                    lines.append("```")
                    lines.append("")
                    lines.append("**Field explanations:**")
                    lines.append("")
                    lines.append("_(see skeleton below — fill in after inspection)_")
                    lines.append("")
                except json.JSONDecodeError:
                    lines.append(f"```\n{text[:500]}\n```")
            elif "protobuf" in mime or text.startswith("\n"):
                lines.append(
                    "⚠️  **Protobuf / binary payload detected.** "
                    "Cannot decode without .proto schema. "
                    "See Pagination notes below."
                )
                dynamic_token_warning = True
            else:
                lines.append(f"```\n{text[:500]}\n```")
            lines.append("")

        # Response
        resp_status = resp.get("status", "?")
        resp_mime = resp.get("content", {}).get("mimeType", "")
        resp_text = resp.get("content", {}).get("text", "")
        lines.append(f"**Response status:** {resp_status}  ")
        lines.append(f"**Response MIME:** `{resp_mime}`")
        lines.append("")

        if resp_text:
            # Save raw sample
            sample_file = SAMPLES_DIR / f"{key.replace('/', '_').replace(' ', '_')}.json"
            try:
                resp_obj = json.loads(resp_text)
                with open(sample_file, "w", encoding="utf-8") as sf:
                    json.dump(resp_obj, sf, indent=2)
                lines.append("### Response skeleton")
                lines.append("")
                lines.append("```")
                lines.append(summarize_json(resp_obj))
                lines.append("```")
                lines.append("")
                lines.append(f"_Sample saved to `docs/samples/{sample_file.name}`_")
                lines.append("")

                # Pagination detection
                resp_str = json.dumps(resp_obj)
                page_tokens = [w for w in ("nextPageToken", "pageToken", "cursor", "next_page_token", "continuation") if w in resp_str]
                if page_tokens:
                    lines.append(f"**Pagination:** response contains `{page_tokens[0]}` — pass as query/body param on next call.")
                    lines.append("")

            except (json.JSONDecodeError, TypeError):
                if "protobuf" in resp_mime or (resp_text and not resp_text.strip().startswith("{")):
                    lines.append(
                        "⚠️  **Binary / non-JSON response.** "
                        "Likely protobuf. Cannot decode without .proto schema."
                    )
                    dynamic_token_warning = True
                else:
                    lines.append(f"```\n{resp_text[:500]}\n```")
                lines.append("")

        lines += ["---", ""]

    # Dynamic token summary
    if dynamic_token_warning:
        lines.insert(
            lines.index("---") + 1,
            "\n## ⚠️  Dynamic Token / Protobuf Warning\n\n"
            "One or more requests carry what appears to be a dynamic token or use "
            "a protobuf payload. These cannot be replicated with static headers. "
            "**Fallback recommendation:** use Playwright response interception "
            "(see `scripts/capture_har.py`) to proxy requests rather than "
            "replicating them with plain httpx.\n",
        )

    DOCS_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Endpoints doc written to: {DOCS_PATH}")
    print(f"Response samples written to: {SAMPLES_DIR}/")

    if dynamic_token_warning:
        print("\n⚠️  WARNING: Dynamic tokens or protobuf payloads detected.")
        print("   Plain httpx replication may not be possible for all endpoints.")
        print("   See docs/endpoints.md for details.")


if __name__ == "__main__":
    main()
